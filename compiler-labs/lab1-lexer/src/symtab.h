/*
 * symtab.h —— 词法阶段的符号表：字符串驻留(string interning)
 * （对照龙书 2.7 节"符号表"接口 + 3.x 词法分析器与符号表的交互）
 *
 * 龙书视角：符号表是编译器的"中央数据库"，词法分析器把标识符的
 * 词素存进去，语法/语义阶段再往里补充类型等信息。
 *
 * 本 lab 只做词法阶段最朴素的一种用法——"驻留"(interning)：
 *   每个不同的标识符字符串在表里只存一份，之后所有同名记号的
 *   lexeme 指针都指向同一份内存。
 * 好处（也是工业界 string interning 的动机）：
 *   1. 之后比较标识符是否同名只需要比指针，不用 strcmp；
 *   2. 省内存：同一个名字出现 1000 次只存 1 份。
 * 顺带记录每个标识符首次出现的行号——你可以直观看到"去重"效果。
 *
 * 实现是教科书式的链地址哈希表（分离链接）：
 *   hash(字符串) % 桶数 -> 桶内单链表上顺序查找。
 * 龙书 2.7 节讨论的"作用域链/嵌套作用域"要到 lab5 才登场。
 */
#ifndef SYMTAB_H
#define SYMTAB_H

/* 把 [start, start+len) 的字符串驻留进符号表，返回它的唯一副本。
 * 若已存在则直接返回旧指针（去重）。同时记录首次出现的行号。 */
const char *symtab_intern(const char *start, int len, int line);

/* 按插入顺序打印所有驻留过的标识符（-s 选项用） */
void symtab_print(void);

#endif /* SYMTAB_H */
